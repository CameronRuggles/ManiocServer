"""OnionHost boot-credentials jobmodule (DESIGN-v3 A19.1 slot layout).

Runs in the exec sequence right after luksbootkeyfile. Two jobs:

1. KEYFILE RELOCATION lives in onionhostcleanup, NOT here: the
   crypttab entry naming the keyfile is written by Calamares' fstab
   job, which runs AFTER this module - at this point in the sequence
   crypttab does not reference the keyfile yet (observed install
   failure, 2026-10-12). onionhostcleanup (just before initramfscfg,
   after fstab) performs the A19.1 relocation.

2. PHRASE SLOT CONVERSION (A19.1: PBKDF2 ONLY). KPMcore enrols the
   install phrase with argon2id, which Debian trixie's signed GRUB
   2.12 cannot derive - the original boot blocker. A19's dual-slot
   layout (argon2id + PBKDF2 twins) was SUPERSEDED by A19.1: offline
   resistance is the minimum over slots, so a twin adds zero
   protection and a silent partial-rotation failure class. This module
   therefore CONVERTS: add a PBKDF2-SHA256 slot for the same phrase,
   verify it with --test-passphrase --key-slot, then KILL the
   argon2id phrase slot. Final layout: MAIN=PBKDF2 (this phrase),
   KEYFILE=random (KDF immaterial). Two slots total: A25 removed
   the spare slot together with the spare feature (2026-10-20).
   Iterations: cryptsetup --iter-time 2000 calibrated on the install
   host (slice 2 retarget: slice 1's 2500 measured 13.2-15.2 s at
   the GRUB prompt on the rig's virtual CPU, too close to the ~15 s
   budget for slower home hardware). Measured on the reference rig
   (GRUB 2.12, nested KVM): host 2000 ms -> 1,464,490 iters ->
   9.05 s GRUB unlock; host 6000 ms -> 4,356,960 iters -> 31.0 s.
   GRUB runs ~5x slower than the host benchmark on the same CPU.

3. GENERATED-PHRASE INTEGRITY (slice 2). The phrase is generated by
   the onionhostphrasegen job and reaches this module through
   GlobalStorage. If the passphrase the partition chain hands us is
   not the generated phrase (e.g. the user typed their own on the
   partition page), the install FAILS LOUDLY: the product contract
   is a generated phrase the user copied to paper, never a typed,
   memorable one.

4. SLOT-ROLE MAP (slice 2). The final slot layout is written to
   /etc/onionhost/luks-roles.json in the target (non-secret):
   which slot is MAIN and which is KEYFILE. onionhost-rekey
   and later Maintenance tooling read it instead of guessing.

Passphrase handling: read from Calamares GlobalStorage
("luksPassphrase") - CAREFUL: ChoicePage stores it OBSCURED via
Calamares::String::obscure() (chars > U+0021 map to
U+1001F - codepoint; the transform is its own inverse). The raw GS
value does NOT open any slot; it must be un-obscured first (verified
against the Calamares 3.3.14 source and empirically: the obscured
form of the 28-char test phrase is 28 code points / 78 UTF-8 bytes
and opens nothing). The un-obscured phrase is written only to 0600
temp files on tmpfs (/dev/shm), shredded in a finally block, never
logged. (The production generated-phrase module will put the phrase
into GlobalStorage programmatically - in obscured form, to match
what downstream Calamares jobs expect.)
"""
import json
import os
import re
import subprocess
import tempfile

import libcalamares

ITER_TIME_MS = "2000"
PBKDF = "pbkdf2"
HASH = "sha256"
KEYFILE_DIR = "/etc/cryptsetup-keys.d"
KEYFILE_NAME = "root.key"
OLD_KEYFILE = "/crypto_keyfile.bin"
ROLEMAP_PATH = "/etc/onionhost/luks-roles.json"


def _fail(msg):
    return ("OnionHost boot credentials", msg, 1)


def _unobscure(value):
    """Inverse of Calamares::String::obscure (it is an involution):
    characters <= U+0021 pass through; others map to U+1001F - cp."""
    return "".join(ch if ord(ch) <= 0x21 else chr(0x1001F - ord(ch))
                   for ch in value)


def _run(args, **kw):
    return subprocess.run(args, capture_output=True, text=True, **kw)


def _luks_dump(device):
    return _run(["cryptsetup", "luksDump", device]).stdout


def _parse_slots(dump):
    """Return {slot_index: {"pbkdf": str}} from luksDump text."""
    slots = {}
    current = None
    for line in dump.splitlines():
        m = re.match(r"\s*(\d+): luks2", line)
        if m:
            current = int(m.group(1))
            slots[current] = {}
            continue
        m = re.match(r"\s*PBKDF:\s*(\S+)", line)
        if m and current is not None:
            slots[current]["pbkdf"] = m.group(1)
    return slots


def _phrase_slots(device, passphrase_file):
    """Slot indexes that the given passphrase opens (via test)."""
    slots = _parse_slots(_luks_dump(device))
    hits = []
    for idx in sorted(slots):
        proc = _run(["cryptsetup", "open", "--test-passphrase",
                     "--key-slot", str(idx),
                     "--key-file", passphrase_file, device])
        if proc.returncode == 0:
            hits.append(idx)
    return hits


def _luks_devices():
    gs = libcalamares.globalstorage
    devices = []
    for part in gs.value("partitions") or []:
        fs = str(part.get("fsName", ""))
        dev = part.get("device")
        if dev and (fs.startswith("luks") or part.get("luksMapperName")):
            devices.append(dev)
    return devices


def _luks_uuid(device):
    for line in _luks_dump(device).splitlines():
        m = re.match(r"\s*UUID:\s*(\S+)", line)
        if m:
            return m.group(1)
    return None


def _fsync_file(path):
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)
    dfd = os.open(os.path.dirname(path), os.O_RDONLY)
    try:
        os.fsync(dfd)
    finally:
        os.close(dfd)


def _write_role_map(root, device, main_slot, keyfile_slot):
    roles = {
        "version": 1,
        "device": device,
        "uuid": _luks_uuid(device),
        "slots": {"MAIN": main_slot, "KEYFILE": keyfile_slot},
        "pbkdf": PBKDF,
        "hash": HASH,
        "iterTimeMs": int(ITER_TIME_MS),
    }
    path = root + ROLEMAP_PATH
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(json.dumps(roles, indent=2, sort_keys=True) + "\n")
    os.chmod(path, 0o644)
    _fsync_file(path)


def run():
    gs = libcalamares.globalstorage
    root = gs.value("rootMountPoint")
    if not root or not os.path.isdir(root):
        return _fail("rootMountPoint missing; cannot fix boot credentials.")
    stored = gs.value("luksPassphrase")
    if not stored:
        return _fail("Install passphrase not available in GlobalStorage "
                     "(luksPassphrase); cannot convert the phrase slot.")
    passphrase = _unobscure(stored)
    # Slice 2 integrity: the passphrase must BE the generated phrase.
    generated = gs.value("onionhostGeneratedPhrase")
    if not generated:
        return _fail("Generated-phrase record missing from "
                     "GlobalStorage (onionhostphrasegen did not run); "
                     "refusing to continue.")
    if _unobscure(generated) != passphrase:
        return _fail("The passphrase entered for the disk is NOT the "
                     "generated passphrase shown on the passphrase "
                     "screen. Installation stopped so the machine is "
                     "never locked to a passphrase that was not "
                     "copied onto paper.")
    devices = _luks_devices()
    if not devices:
        return _fail("No LUKS device found in GlobalStorage partitions.")
    if len(devices) != 1:
        return _fail("Expected exactly one LUKS device, found %d; "
                     "the slot-role map requires a single-device "
                     "layout." % len(devices))

    tmpdir = tempfile.mkdtemp(prefix="onionhost-bootkey-", dir="/dev/shm")
    os.chmod(tmpdir, 0o700)
    pass_file = os.path.join(tmpdir, "phrase")
    new_file = os.path.join(tmpdir, "phrase-new")
    secret_files = [pass_file, new_file]
    try:
        for path in (pass_file, new_file):
            with open(path, "w") as f:
                f.write(passphrase)
            os.chmod(path, 0o600)
        for device in devices:
            before = _parse_slots(_luks_dump(device))
            phrase_hits = _phrase_slots(device, pass_file)
            argon_phrase = [i for i in phrase_hits
                            if before.get(i, {}).get("pbkdf") == "argon2id"]
            pbkdf_phrase = [i for i in phrase_hits
                            if before.get(i, {}).get("pbkdf") == "pbkdf2"]
            if argon_phrase and not pbkdf_phrase:
                proc = _run(["cryptsetup", "luksAddKey", "--batch-mode",
                             "--pbkdf", PBKDF, "--hash", HASH,
                             "--iter-time", ITER_TIME_MS,
                             "--key-file", pass_file, device, new_file])
                if proc.returncode != 0:
                    return _fail("luksAddKey (PBKDF2) failed for %s: %s"
                                 % (device, proc.stderr.strip()[:400]))
                pbkdf_phrase = [i for i in _phrase_slots(device, pass_file)
                                if _parse_slots(_luks_dump(device))
                                .get(i, {}).get("pbkdf") == "pbkdf2"]
                if not pbkdf_phrase:
                    return _fail("PBKDF2 slot for the phrase not verified "
                                 "on %s after luksAddKey." % device)
            # Kill every remaining argon2id slot the PHRASE opens.
            # (The keyfile slot is argon2id too, but the phrase does
            # not open it, so it is never in phrase_hits.)
            for idx in _phrase_slots(device, pass_file):
                slot = _parse_slots(_luks_dump(device)).get(idx, {})
                if slot.get("pbkdf") == "argon2id":
                    # luksKillSlot demands proof of a remaining key:
                    # supply the phrase file (it opens the new PBKDF2
                    # slot). Without --key-file it prompts and fails
                    # non-interactively ("No key available").
                    proc = _run(["cryptsetup", "luksKillSlot",
                                 "--key-file", pass_file,
                                 device, str(idx)])
                    if proc.returncode != 0:
                        return _fail("luksKillSlot %d failed for %s: %s"
                                     % (idx, device,
                                        proc.stderr.strip()[:400]))
            final = _phrase_slots(device, pass_file)
            final_slots = _parse_slots(_luks_dump(device))
            if len(final) != 1 or \
                    final_slots.get(final[0], {}).get("pbkdf") != "pbkdf2":
                return _fail("Final phrase-slot layout on %s is not "
                             "exactly one PBKDF2 slot: %s"
                             % (device, final_slots))
            # --- slot-role map --------------------------------------
            occupied = sorted(_parse_slots(_luks_dump(device)))
            others = [i for i in occupied if i != final[0]]
            if len(others) != 1:
                return _fail("Cannot determine the KEYFILE slot on "
                             "%s: occupied=%s main=%s"
                             % (device, occupied, final))
            _write_role_map(root, device, final[0], others[0])
    finally:
        for path in secret_files:
            try:
                with open(path, "wb") as f:
                    f.write(os.urandom(4096))
                os.unlink(path)
            except OSError:
                pass
        try:
            os.rmdir(tmpdir)
        except OSError:
            pass
    return None
