"""OnionHost passphrase generation (DESIGN-v3 A19.1 entropy gate).

Implementation shared by:
  * the first-boot wizard (3-word login phrase),
  * onionhost-rekey (7-word replacement disk phrase).

The installer's disk phrase is generated by the C++ phrase view
step (OnionHostPhraseViewStep), which contains a port of this exact
algorithm - Calamares 3.3 runs job modules only in the exec phase,
so generation cannot happen in a show-phase Python job there.

Entropy: os.urandom(), which on Linux is getrandom(2) called WITHOUT
GRND_NONBLOCK (CPython Modules/_randommodule.c / Python/fileutils via
pyurandom) - the call BLOCKS until the kernel CSPRNG is seeded, then
draws from the kernel pool. No userspace PRNG, no seed files, no
Math.random-style shortcuts anywhere in the chain.

Sampling: rejection sampling over whole random bytes. For the EFF
large wordlist (n = 7776 < 2**13) each candidate uses 13 bits taken
from 2 fresh random bytes masked to 13 bits (masking to a power of
two is unbiased); candidates >= 7776 are DISCARDED and redrawn. There
is no modulo anywhere, so every word is equiprobable
(A19.1: "no modulo bias").

Wordlist: /usr/share/onionhost/eff-large-wordlist.txt - the EFF large
(Diceware) list, 7776 entries, sha256 of the vendored file
addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e.
Count and uniqueness are asserted on every load (and again at ISO
build time); a tampered or truncated list raises instead of silently
shrinking the phrase space.
"""
import os

WORDLIST_PATH = "/usr/share/onionhost/eff-large-wordlist.txt"
EXPECTED_WORDS = 7776

_cache = None


def load_words():
    global _cache
    if _cache is not None:
        return _cache
    words = []
    with open(WORDLIST_PATH, encoding="utf-8") as f:
        for line in f:
            parts = line.split()
            if parts:
                words.append(parts[-1])
    if len(words) != EXPECTED_WORDS:
        raise RuntimeError(
            "wordlist has %d entries, expected %d"
            % (len(words), EXPECTED_WORDS))
    if len(set(words)) != EXPECTED_WORDS:
        raise RuntimeError("wordlist entries are not unique")
    _cache = words
    return words


def _randbelow(n):
    """Uniform integer in [0, n) via rejection sampling on
    os.urandom bytes. Candidates are masked to ceil(log2(n)) bits;
    any candidate >= n is discarded. Never uses modulo."""
    nbits = (n - 1).bit_length()
    nbytes = (nbits + 7) // 8
    mask = (1 << nbits) - 1
    while True:
        candidate = int.from_bytes(os.urandom(nbytes), "big") & mask
        if candidate < n:
            return candidate


def generate(nwords):
    """Return a space-separated phrase of nwords words."""
    words = load_words()
    return " ".join(words[_randbelow(len(words))]
                    for _ in range(nwords))


def obscure(value):
    """Calamares::String::obscure (3.3.14, String.cpp): characters
    <= U+0021 pass through; others map to U+1001F - codepoint.
    The transform is an involution, so this also un-obscures."""
    return "".join(ch if ord(ch) <= 0x21 else chr(0x1001F - ord(ch))
                   for ch in value)


unobscure = obscure


if __name__ == "__main__":
    import sys
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 7
    print(generate(n))
